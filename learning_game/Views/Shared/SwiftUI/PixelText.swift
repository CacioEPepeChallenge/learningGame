//  A tiny 5×7 bitmap font drawn with Canvas, for the pixel-art window titles
//  ("DEFINING A FUNCTION", "IRIS", …) seen in the UI mockups. No font file needed.
//

import SwiftUI

struct PixelText: View {
    let text: String
    var color: Color = .white
    /// Size of one font pixel, in points.
    var pixel: CGFloat = 2
    /// Gap between glyphs, in font pixels.
    var tracking: Int = 2

    var body: some View {
        let glyphs = text.uppercased().map { PixelFont.glyph(for: $0) }
        let widthInPixels = glyphs.reduce(0) { $0 + $1.width } + max(glyphs.count - 1, 0) * tracking

        Canvas { context, _ in
            var x = 0
            for glyph in glyphs {
                for (row, line) in glyph.rows.enumerated() {
                    for (col, bit) in line.enumerated() where bit == "#" {
                        let rect = CGRect(x: CGFloat(x + col) * pixel,
                                          y: CGFloat(row) * pixel,
                                          width: pixel, height: pixel)
                        context.fill(Path(rect), with: .color(color))
                    }
                }
                x += glyph.width + tracking
            }
        }
        .frame(width: CGFloat(widthInPixels) * pixel, height: 7 * pixel)
        .accessibilityElement()
        .accessibilityLabel(text)
        .accessibilityAddTraits(.isHeader)
    }
}

